"""Generates the sorting networks of calx_sort.h, for integers' short runs (D157).

    py -I tools/sort_networks.py > networks.h

Each is Batcher's odd-even merge sort for 4, 8, 16 or 32 elements: 5, 19, 63 and 191 comparators,
3, 6, 10 and 15 deep. A comparator puts the lesser of two elements first. They're printed a layer
to a line, where no comparator waits on another, so the compiler can run a layer at once, with
`cmov`s or, for x86-64-v3, vector compares.

The script checks each network by the 0-1 principle: a network that sorts every list of zeros and
ones sorts every list. That's every such list up to 16 elements, and 200,000 random ones of 32.
"""
import random
import sys


def merge(lo, n, r):
    """Merges the sorted halves of lo..lo+n, comparing elements r apart."""
    step = r * 2
    if step < n:
        yield from merge(lo, n, step)
        yield from merge(lo + r, n, step)
        for i in range(lo + r, lo + n - r, step):
            yield (i, i + r)
    else:
        yield (lo, lo + r)


def batcher(lo, n):
    if n > 1:
        half = n // 2
        yield from batcher(lo, half)
        yield from batcher(lo + half, half)
        yield from merge(lo, n, 1)


def layers(net):
    """The comparators in layers, each after every comparator it depends on."""
    depth = {}
    out = []
    for i, j in net:
        d = max(depth.get(i, 0), depth.get(j, 0))
        while len(out) <= d:
            out.append([])
        out[d].append((i, j))
        depth[i] = depth[j] = d + 1
    return out


def check(net, n):
    rng = random.Random(1)
    cases = range(1 << n) if n <= 16 else (rng.getrandbits(n) for _ in range(200000))
    for bits in cases:
        x = [(bits >> k) & 1 for k in range(n)]
        for i, j in net:
            if x[i] > x[j]:
                x[i], x[j] = x[j], x[i]
        assert all(x[k] <= x[k + 1] for k in range(n - 1)), (n, bits)


def wrap(items, first, rest=None, width=110):
    """`items` joined by spaces, in lines of at most `width`, the first after `first` and the rest
    after `rest`, which is as many spaces as `first` unless given."""
    rest = " " * len(first) if rest is None else rest
    lines, line, start = [], first, first
    for item in items:
        if len(line) + len(item) + 1 > width and len(line) > len(start):
            lines.append(line.rstrip())
            line = start = rest
        line += item + " "
    lines.append(line.rstrip())
    return lines


sizes = {4: (5, 3), 8: (19, 6), 16: (63, 10), 32: (191, 15)}
out = ["/* Generated by tools/sort_networks.py. */"]
for n, (count, deep) in sizes.items():
    net = list(batcher(0, n))
    check(net, n)
    assert (len(net), len(layers(net))) == (count, deep), n
    out.append(f"static inline void CX_SORT_F(_net{n})(CX_SORT_T* v) {{")
    out += wrap([f"x{k} = v[{k}]," for k in range(n - 1)] + [f"x{n - 1} = v[{n - 1}];"], "    CX_SORT_T ")
    for layer in layers(net):
        out += wrap([f"CX_SORT_CAS(x{i}, x{j});" for i, j in layer], "    ")
    out += wrap([f"v[{k}] = x{k};" for k in range(n)], "    ")
    out.append("}")
    out.append("")
sys.stdout.write("\n".join(out))
