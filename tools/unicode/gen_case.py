"""Writes the tables in runtime/calx_case.c from what Java does to each code point.

Usage, from the repository's root, with Java 25:

    java tools/unicode/CaseDump.java build/cases.txt
    py tools/unicode/gen_case.py build/cases.txt

CaseDump.java writes, for each code point, what String.toLowerCase and toUpperCase give with
Locale.ROOT, how Java's word BreakIterator treats it, and whether it's cased, which is what Java
decides a capital sigma's lowercase by. This script packs that into a two-stage table: the code
point's block, then its kind, which holds the two case deltas, the word class and flags. The
mapping is the Unicode Character Database's, as Java 25 has it (Unicode 16).
"""

import sys
from pathlib import Path

CLASSES = ["O", "L", "D", "MW", "MWN", "MN", "POST", "WS", "CR", "LS", "X", "XF", "K", "H", "KA", "DANDA"]
CASED, UP_MANY, LOW_MANY, SIGMA = 1, 2, 4, 8
DENSE = 0x40000  # past this, only plane 14 has anything, which `kind_of` tests by range
BEGIN = "/* --- generated by tools/unicode/gen_case.py; don't edit by hand --- */\n"
END = "/* --- end of the generated tables --- */\n"
# The tables are the Unicode Character Database's case mappings and word classes, as Java has them.
