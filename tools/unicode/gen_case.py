def load(path):
    rows = {}
    java = None
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            java = line[1:].strip()
            continue
        cp, lo, up, cls, cased = line.split()
        cp = int(cp, 16)
        lo = [cp] if lo == "same" else [int(x, 16) for x in lo.split(",")]
        up = [cp] if up == "same" else [int(x, 16) for x in up.split(",")]
        rows[cp] = (lo, up, CLASSES.index(cls), cased == "1")
    return java, rows


def kind_of(cp, row):
    lo, up, cls, cased = row
    flags = CASED if cased else 0
    lower = upper = 0
    if len(lo) == 1:
        lower = lo[0] - cp
    else:
        flags |= LOW_MANY
    if len(up) == 1:
        upper = up[0] - cp
    else:
        flags |= UP_MANY
    if cp == 0x3A3:
        flags |= SIGMA
    return (lower, upper, cls, flags)


def main():
    java, rows = load(sys.argv[1])
    low_many = {cp: r[0] for cp, r in rows.items() if len(r[0]) != 1}
    assert list(low_many) == [0x130] and low_many[0x130] == [0x69, 0x307], low_many
    up_many = sorted((cp, r[1]) for cp, r in rows.items() if len(r[1]) != 1)
    assert all(len(u) <= 3 for _, u in up_many)
    # Past DENSE, only marks and format characters, with no case: tested by range in C.
    far = sorted((cp, r) for cp, r in rows.items() if cp >= DENSE)
    for cp, (lo, up, cls, cased) in far:
        assert lo == [cp] and up == [cp] and not cased and CLASSES[cls] in ("X", "XF"), hex(cp)
    far_ranges = []
    for cp, (_, _, cls, _) in far:
        if far_ranges and far_ranges[-1][1] == cp - 1 and far_ranges[-1][2] == cls:
            far_ranges[-1][1] = cp
        else:
            far_ranges.append([cp, cp, cls])

    kinds = [(0, 0, 0, 0)]
    index = {kinds[0]: 0}
    per_cp = [0] * DENSE
    for cp, r in rows.items():
        if cp >= DENSE:
            continue
        k = kind_of(cp, r)
        if k not in index:
            index[k] = len(kinds)
            kinds.append(k)
        per_cp[cp] = index[k]
    assert len(kinds) <= 256, len(kinds)

    best = None
    for shift in (4, 5, 6, 7, 8):
        size = 1 << shift
        blocks = []
        bindex = {}
        stage1 = []
        for b in range(DENSE >> shift):
            block = tuple(per_cp[b * size:(b + 1) * size])
            if block not in bindex:
                bindex[block] = len(blocks)
                blocks.append(block)
            stage1.append(bindex[block])
        s1_bytes = 1 if len(blocks) <= 256 else 2
        total = len(stage1) * s1_bytes + len(blocks) * size
        if best is None or total < best[0]:
            best = (total, shift, stage1, blocks, s1_bytes)
    total, shift, stage1, blocks, s1_bytes = best

    def array(ctype, name, values, per_line=24):
        lines = []
        for i in range(0, len(values), per_line):
            lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
        return f"static const {ctype} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"

    out = [BEGIN, NOTICE]
    out.append(f"/* From {java}: {len(rows)} code points, {len(kinds)} kinds, blocks of {1 << shift}, "
               f"{total + len(kinds) * 12 + len(up_many) * 16} bytes. */\n")
    out.append("enum { " + ", ".join(f"W_{c}" for c in CLASSES) + " };\n")
    out.append(f"enum {{ CASED = {CASED}, UP_MANY = {UP_MANY}, LOW_MANY = {LOW_MANY}, SIGMA = {SIGMA} }};\n")
    out.append("typedef struct { cx_i32 lower, upper; cx_u8 word, flags; } case_kind;\n")
    out.append(f"static const case_kind kinds[{len(kinds)}] = {{\n")
    for i in range(0, len(kinds), 4):
        out.append("    " + " ".join("{%d, %d, %d, %d}," % k for k in kinds[i:i + 4]) + "\n")
    out.append("};\n")
    out.append(array("cx_u8" if s1_bytes == 1 else "cx_u16", "stage1", stage1))
    flat = [v for b in blocks for v in b]
    out.append(array("cx_u8", "stage2", flat, 32))
    out.append(f"/* Uppercase that's more than one code point, as ß is SS, by code point. */\n")
    out.append(f"static const struct {{ cx_u32 cp, to[3]; }} up_many[{len(up_many)}] = {{\n")
    for i in range(0, len(up_many), 3):
        out.append("    " + " ".join("{0x%X, {%s}}," % (cp, ", ".join("0x%X" % c for c in (u + [0, 0])[:3]))
                                     for cp, u in up_many[i:i + 3]) + "\n")
    out.append("};\n")
    out.append("static inline const case_kind* kind_of(cx_u32 cp) {\n")
    out.append(f"    if (__builtin_expect(cp < 0x{DENSE:X}, 1)) return &kinds[stage2[(cx_u32)stage1[cp >> {shift}] << {shift} | (cp & {(1 << shift) - 1})]];\n")
    for lo, hi, cls in far_ranges:
        k = (0, 0, cls, 0)
        if k not in index:
            raise SystemExit(f"no kind for class {CLASSES[cls]} far out")
        cond = f"cp == 0x{lo:X}" if lo == hi else f"cp >= 0x{lo:X} && cp <= 0x{hi:X}"
        out.append(f"    if ({cond}) return &kinds[{index[k]}];\n")
    out.append("    return &kinds[0];\n}\n")
    out.append(END)

    path = Path("runtime/calx_case.c")
    text = path.read_text(encoding="utf-8")
    a, b = text.index(BEGIN), text.index(END) + len(END)
    path.write_text(text[:a] + "".join(out) + text[b:], encoding="utf-8", newline="\n")
    print(f"{len(kinds)} kinds, blocks of {1 << shift}, {len(blocks)} blocks, {total} bytes of stages")


if __name__ == "__main__":
    main()
