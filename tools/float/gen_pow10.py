"""Writes the table of powers of ten in runtime/calx_float.c.

    py -I tools/float/gen_pow10.py

Entry i is the significand of 10^(i - 293) in 128 bits, rounded down: the integer in
[2^127, 2^128) that is 10^e times a power of two, less what's past its last bit. Python's
integers are exact, so each entry is too. Żmij's printing reads the entry for 10^(-k - 1), for
every k a double or a float can scale by, which runs from -293 to 324.
"""
from pathlib import Path

FIRST, COUNT = -293, 618
BEGIN = "/* --- generated by tools/float/gen_pow10.py; don't edit by hand --- */\n"
END = "/* --- end of the generated table --- */\n"
M64 = (1 << 64) - 1


def significand(e):
    if e >= 0:
        v = 10 ** e
        n = v.bit_length()
        sig = v << (128 - n) if n <= 128 else v >> (n - 128)
    else:
        p = 10 ** -e
        sig = (1 << (p.bit_length() + 127)) // p
    assert 1 << 127 <= sig < 1 << 128
    return sig


def main():
    out = [BEGIN, f"static const pow10_sig POW10[{COUNT}] = {{\n"]
    for i in range(COUNT):
        sig = significand(FIRST + i)
        out.append(f"    {{0x{sig >> 64:016x}, 0x{sig & M64:016x}}},  /* 10^{FIRST + i} */\n")
    out.append("};\n")
    out.append(END)
    path = Path("runtime/calx_float.c")
    text = path.read_text(encoding="utf-8")
    a, b = text.index(BEGIN), text.index(END) + len(END)
    path.write_text(text[:a] + "".join(out) + text[b:], encoding="utf-8", newline="\n")
    print(f"{COUNT} powers of ten, 10^{FIRST} to 10^{FIRST + COUNT - 1}")


if __name__ == "__main__":
    main()
