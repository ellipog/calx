"""Writes the table of powers of five in runtime/calx_fparse.c.

    py -I tools/float/gen_pow5.py

Entry i is the significand of 5^(i - 342) in 128 bits, rounded down: the integer in
[2^127, 2^128) that is 5^q times a power of two, less what's past its last bit. The entries for
q from 0 to 55 are exact, since 5^55 fits in 128 bits; the rest are less than the true value by
less than one in their last bit, which is what the parser's error bound assumes. Python's
integers are exact, so each entry is too.

It checks, too, that the binary exponent the parser works out with a multiply and a shift,
floor(log2(5^q)) = (q * 152170) >> 16, holds for every q in the table.
"""
from pathlib import Path

FIRST, LAST = -342, 308
BEGIN = "/* --- generated by tools/float/gen_pow5.py; don't edit by hand --- */\n"
END = "/* --- end of the generated table --- */\n"
M64 = (1 << 64) - 1


def significand(q):
    if q >= 0:
        v = 5 ** q
        n = v.bit_length()
        sig = v << (128 - n) if n <= 128 else v >> (n - 128)
        exact = n <= 128
        log2 = n - 1
    else:
        d = 5 ** -q
        sig = (1 << (d.bit_length() + 127)) // d
        exact = False
        log2 = -d.bit_length()  # 5^q is between 2^-n and 2^(1-n), and never a power of two
    assert 1 << 127 <= sig < 1 << 128
    assert (q * 152170) >> 16 == log2, q
    assert exact == (0 <= q <= 55)
    return sig


def main():
    rows = []
    for q in range(FIRST, LAST + 1):
        s = significand(q)
        rows.append(f"    {{0x{s >> 64:016x}, 0x{s & M64:016x}}},  /* 5^{q} */\n")
    table = (BEGIN + f"#define POW5_FIRST ({FIRST})\n#define POW5_LAST {LAST}\n"
             "static const cx_u64 pow5[][2] = {\n" + "".join(rows) + "};\n" + END)
    path = Path(__file__).resolve().parents[2] / "runtime" / "calx_fparse.c"
    text = path.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    path.write_text(text[:start] + table + text[end:], encoding="utf-8", newline="\n")
    print(f"wrote {LAST - FIRST + 1} entries to {path}")


main()
